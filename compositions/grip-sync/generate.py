def _num(v):
    r = round(float(v), 4)
    return str(int(r)) if r == int(r) else str(r)


def _sec(v):
    return str(round(float(v), 4))


def parse_clips(path):
    """The bounded clip-table subset the entry uses: 2-space clip names, 4-space
    set:/curves:/length rows, 6-space quoted bindings. Values stay verbatim
    strings so a transcribed value is byte-exact; dict order is the entry's."""
    clips, cur, sect, started = {}, None, None, False
    for line in open(path, encoding="utf-8"):
        if re.match(r"^clips:", line):
            started, cur = True, None
            continue
        if not started:
            continue
        m = re.match(r"^  ([\w+-]+):", line)
        if m:
            cur, sect = m.group(1), None
            clips[cur] = {"set": {}, "curves": {}, "len": None}
            continue
        if cur is None:
            continue
        m = re.match(r"^    (?:length|seconds): ([\d.]+)", line)
        if m:
            clips[cur]["len"] = m.group(1)
            continue
        if re.match(r"^    set:", line):
            sect = "set"
            continue
        if re.match(r"^    curves:", line):
            sect = "curves"
            continue
        m = re.match(r'^      "([^"]+)": (.+?)\s*$', line)
        if m and sect:
            clips[cur][sect][m.group(1)] = m.group(2)
            continue
        if line.strip() and not line.lstrip().startswith("#"):
            # A row this bounded parser does not model would otherwise vanish from the emitted table
            # (a dwell dropping to one frame, a binding unwritten) with nothing failing anywhere.
            raise SystemExit(f"REFUSE: unparsed clip-table row in {os.path.basename(path)} under `{cur}`: {line.rstrip()}")
    return clips


def emit_clips(cell):
    pulse = float(cell["released"]["len"])
    dwells = {"BRIDGE": BRIDGE, "RESUME": pulse + BRIDGE, "ACQUIRE": ACQUIRE_LEN}
    out = []
    for name, src, setname, dwell, note in CLIPS:
        if src not in cell:
            raise SystemExit(f"REFUSE: absolute-grip-prop/controller.yaml has no clip `{src}` — "
                             f"`{name}` transcribes it. Reconcile CLIPS against the entry's table.")
        e = cell[src]
        vals = VALUE_SETS[setname]
        rows, curves = {GLUE_KEYS[0]: _num(vals[0])}, {}
        for k, v in e["set"].items():
            rows[PREFIX + k] = v
        for k, v in e["curves"].items():
            curves[PREFIX + k] = v
        if GP0 not in rows or GP1 not in rows:
            raise SystemExit(f"REFUSE: cell clip `{src}` does not write GrabPosition's two source weights — the GrabPosition carve has nothing to carve")
        if ROTOR_EN not in rows or ROTOR_S0 not in rows:
            raise SystemExit(f"REFUSE: cell clip `{src}` does not write Rotor's enable and home "
                             "weight — the Rotor carve has nothing to carve")
        rows[ROTOR_S3] = "0"
        if name in WORD_STATES:
            rows[GP0], rows[GP1] = "1", "0"
            rows[ROTOR_EN], rows[ROTOR_S0], rows[ROTOR_S3] = "1", "0", "1"
        for k, v in zip(GLUE_KEYS[1:], vals[1:]):
            if v is None:
                curves[k] = DISPLAY_DELAY
            else:
                rows[k] = _num(v)
        length = dwells[dwell] if isinstance(dwell, str) else dwell
        if length is None and e["len"]:
            length = float(e["len"])
        text = [t.format(PULSE=_sec(pulse), BRIDGE=_sec(BRIDGE), RESUME=_sec(pulse + BRIDGE))
                for t in note]
        head = f"  {name}:"
        out.append(head + " " * max(1, 18 - len(head)) + "# " + text[0])
        out.extend(" " * 18 + "# " + t for t in text[1:])
        if length is not None:
            out.append(f"    length: {_sec(length)}")
        out.append("    set:")
        out.extend(f'      "{k}": {v}' for k, v in rows.items())
        if curves:
            out.append("    curves:")
            out.extend(f'      "{k}": {v}' for k, v in curves.items())
    return out


def splice(path, begin, end, body):
    lines = open(path, encoding="utf-8").read().split("\n")
    bi = [i for i, l in enumerate(lines) if l == begin]
    ei = [i for i, l in enumerate(lines) if l == end]
    if len(bi) != 1 or len(ei) != 1 or bi[0] >= ei[0]:
        raise SystemExit(f"REFUSE: {os.path.basename(path)} must carry exactly one marker pair, "
                         f"in order — found {len(bi)} begin, {len(ei)} end.")
    out = lines[:bi[0] + 1] + body + lines[ei[0]:]
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    return len(body)


