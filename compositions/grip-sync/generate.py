def load(path, name):
    if not os.path.exists(path):
        raise SystemExit(f"REFUSE: {path} is missing — this composition drives that "
                         "entry's generator and cannot emit without it.")
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def sync_config(mod):
    cfg = dict(mod.CONFIG)
    cfg["objects"] = [{"name": "Prop", "rotation": "full"}]
    cfg["mountPath"] = MOUNT
    return cfg


# ================================================================ readout ===
def readout_text(grip):
    """The entry's readout document with every scene-binding path under PREFIX.
    Scene bindings are the quoted keys in `clips:`; parameter keys are bare.
    Refuses on a quoted key outside the entry's tip subtree, which would mean the
    entry grew a binding this prefix rule does not know."""
    text = grip.emit_readout()
    head, sep, clips = text.partition("\nclips:\n")
    if not sep:
        raise SystemExit("REFUSE: the readout document has no clips: block")
    bad = sorted({k for k in re.findall(r'"([^"]+)"', clips)
                  if not k.startswith("GrabPosition/")})
    if bad:
        raise SystemExit(f"REFUSE: readout scene bindings outside GrabPosition/: {bad[:5]}")
    clips = clips.replace('"GrabPosition/', f'"{PREFIX}GrabPosition/')
    n = clips.count(f'"{PREFIX}')
    head = head.replace(
        "# GENERATED by generate.py -- edit the generator, not this file.",
        "# GENERATED by compositions/grip-sync/generate.py from absolute-grip-prop's generator, "
        f"unmodified, then every scene binding prefixed {PREFIX} (the nested entry's mount).\n"
        "# Edit the ENTRY generator, never this file.", 1)
    return head + sep + clips, n


