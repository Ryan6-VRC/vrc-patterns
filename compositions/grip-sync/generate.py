#!/usr/bin/env python3
"""grip-sync: the two entry generators driven unmodified, plus this composition's
own glue clip table.

    python compositions/grip-sync/generate.py           # writes the three documents
    python compositions/grip-sync/generate.py --check   # asserts the prefab's silent surface, writes nothing

Three documents, three builds, ONE FullController on the prefab root:

  object-sync/controller.yaml   the object-sync entry's generator at CONFIG
                                `objects: [{Prop, full}]`, `mountPath "ObjectSync"`
                                (the nested sync rig's GO name under the root);
                                default rigSeed, so the nested rig is the entry's
                                own committed root prefab.
  readout/controller.yaml       absolute-grip-prop's readout document, emitted by
                                its generator unmodified, then every scene-binding
                                path prefixed with the nested entry's mount
                                (`Prop/AbsoluteGripProp/`) — a textual deviation
                                after the emit, the same shape the cell prefix
                                below takes. The entry generator has no mount
                                knob and this composition does not add one.
  controller.yaml               the glue (hand-authored graph above the marker;
                                the clip table below it is emitted here).

Why one component: the glue reads the sync build's sealed `OS/Ready` and the
readout's `Palm/*` AAPs. One FullController prefixes every controller it merges
identically, so those names unify with nothing published beyond the sync
build's own derived `globalParams`. Controller order in that component is
load-bearing: the glue sits FIRST in both the controllers list and the prms
list, so its `ObjectSync/Enable` declaration (default 1) wins the first-wins
parameter merge in each (controller.yaml's header owns the mechanism; --check
pins both orders). The readout sits between; it declares no name the other two
declare, so its position is free and is not pinned.

THE GLUE CLIP TABLE
-------------------
Cell bindings are read live from ../../absolute-grip-prop/controller.yaml's clip
table at emit time under PREFIX; CLIPS maps each glue clip to an entry clip by
NAME. Freezing a cell value here forks the entry (CONVENTIONS.md §compositions/).
The only literals here are glue-side: GLUE_KEYS, VALUE_SETS, the dwells, the
two carves and the per-clip notes.

Two carves, and only two, depart from the cell's values:

  GP_CARVE     grab-sync's: GrabPosition weights (1,0) in the word states, so the
               parked cell root rides the word through the repointed Display
               (../../grab-prop/README.md §How it works sanctions the repoint).
  ROTOR_CARVE  this composition's own: `Container/Rotor` gains a fourth source,
               `ObjectSync/Sync`, and in the word states the clip writes
               `Rotor.m_Enabled 1, source0 0, source3 1` (weights normalize by
               sum, so home must go to 0). Every other clip writes source3 = 0
               and the cell's own Rotor values. The cell freezes Rotor
               (m_Enabled 0) in acquire/latched/reacquire/settling/settled/
               released/dropped and re-enables it on the grip only in carry*,
               so on a remote the freeze holds the WORD's attitude from Synced
               through Grip Settled and the grip eases from it at Confirm —
               the park that replaces grab-sync's drag-heading park, with no
               second writer on Rotor (Damped's rotation smoother is unbound
               and always chases Rotor). This is the first composition to add a
               source inside the cell subtree; the capture edge
               (Container <- SourcePosition) is hierarchy-authored and outranks
               it, and the new ring's stale edges are measured, not inherited
               (README §Verifying it).
"""

