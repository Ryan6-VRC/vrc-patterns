def prefab_docs(path):
    # A nested instance's transforms serialize as `--- !u!4 &<id> stripped` documents; keep them, the check resolves them.
    return [(int(m.group(1)), int(m.group(2)), m.group(3)) for m in re.finditer(
        r"^--- !u!(\d+) &(\d+)(?: stripped)?\n(.*?)(?=^--- |\Z)", open(path, encoding="utf-8").read(), re.M | re.S)]


def entry_prefab(rel):
    """(guid, {fileID: (own name, parent name)} over transforms, {component fileID: owner name})."""
    prefab = os.path.join(PATTERNS, rel)
    guid = re.search(r"guid: (\w+)", open(prefab + ".meta", encoding="utf-8").read()).group(1)
    docs = prefab_docs(prefab)
    go_name = {a: re.search(r"m_Name: (.*)", b).group(1).strip() for c, a, b in docs if c == 1 and "m_Name:" in b}
    owner = {a: go_name.get(int(re.search(r"m_GameObject: \{fileID: (\d+)", b).group(1)), "?")
             for c, a, b in docs if c in (4, 114) and "m_GameObject:" in b}
    father = {a: int(re.search(r"m_Father: \{fileID: (\d+)", b).group(1)) for c, a, b in docs if c == 4}
    transforms = {a: (owner[a], owner.get(father[a], "<root>")) for a in father}
    comps = {a: (owner[a], b) for c, a, b in docs if c == 114}
    return guid, transforms, comps, docs


